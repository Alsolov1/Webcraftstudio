-- WEBCRAFT customer requests module
-- Run this in Supabase SQL Editor AFTER the admin_users table and admin account are configured.

create table if not exists public.customer_requests (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 160),
  email text not null check (char_length(email) between 3 and 254),
  phone text not null default '',
  service text not null default '',
  budget text not null default '',
  message text not null check (char_length(message) between 1 and 10000),
  status text not null default 'new' check (status in ('new','contacted','in_progress','closed')),
  created_at timestamptz not null default now()
);

alter table public.customer_requests enable row level security;

-- Visitors may submit a request, but cannot read or modify any request.
grant insert on table public.customer_requests to anon, authenticated;
grant select, update, delete on table public.customer_requests to authenticated;
grant usage, select on sequence public.customer_requests_id_seq to anon, authenticated;

drop policy if exists "Anyone can submit a customer request" on public.customer_requests;
create policy "Anyone can submit a customer request"
on public.customer_requests for insert to anon, authenticated
with check (
  status = 'new'
  and char_length(trim(name)) > 0
  and char_length(trim(email)) >= 3
  and char_length(trim(message)) > 0
);

drop policy if exists "Admins can read customer requests" on public.customer_requests;
create policy "Admins can read customer requests"
on public.customer_requests for select to authenticated
using (exists (
  select 1 from public.admin_users au where au.user_id = auth.uid()
));

drop policy if exists "Admins can update customer requests" on public.customer_requests;
create policy "Admins can update customer requests"
on public.customer_requests for update to authenticated
using (exists (
  select 1 from public.admin_users au where au.user_id = auth.uid()
))
with check (exists (
  select 1 from public.admin_users au where au.user_id = auth.uid()
));

drop policy if exists "Admins can delete customer requests" on public.customer_requests;
create policy "Admins can delete customer requests"
on public.customer_requests for delete to authenticated
using (exists (
  select 1 from public.admin_users au where au.user_id = auth.uid()
));
